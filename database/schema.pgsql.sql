CREATE TYPE billing_cycle_t   AS ENUM ('monthly', 'annual');
CREATE TYPE sub_status_t      AS ENUM ('active', 'cancelled');
CREATE TYPE payment_status_t  AS ENUM ('paid', 'pending', 'failed');

CREATE TABLE IF NOT EXISTS users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(120) NOT NULL,
    email         VARCHAR(190) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    business_name VARCHAR(150) NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS customers (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name        VARCHAR(150) NOT NULL,
    email       VARCHAR(190) NOT NULL,
    phone       VARCHAR(30)  NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_customers_user ON customers(user_id);

CREATE TABLE IF NOT EXISTS plans (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        INTEGER        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    plan_name      VARCHAR(100)   NOT NULL,
    price          NUMERIC(10,2)  NOT NULL,
    billing_cycle  billing_cycle_t NOT NULL DEFAULT 'monthly',
    description    VARCHAR(255)   NULL,
    created_at     TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_plans_user ON plans(user_id);

CREATE TABLE IF NOT EXISTS subscriptions (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       INTEGER      NOT NULL REFERENCES users(id)     ON DELETE CASCADE,
    customer_id   INTEGER      NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    plan_id       INTEGER      NOT NULL REFERENCES plans(id)     ON DELETE RESTRICT,
    start_date    DATE         NOT NULL,
    renewal_date  DATE         NOT NULL,
    status        sub_status_t NOT NULL DEFAULT 'active',
    cancelled_at  DATE         NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_subscriptions_user    ON subscriptions(user_id);
CREATE INDEX IF NOT EXISTS idx_subscriptions_status  ON subscriptions(status);
CREATE INDEX IF NOT EXISTS idx_subscriptions_renewal ON subscriptions(renewal_date);

CREATE TABLE IF NOT EXISTS payments (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id  INTEGER          NOT NULL REFERENCES subscriptions(id) ON DELETE CASCADE,
    amount           NUMERIC(10,2)    NOT NULL,
    payment_date     DATE             NOT NULL,
    payment_status   payment_status_t NOT NULL DEFAULT 'paid'
);
CREATE INDEX IF NOT EXISTS idx_payments_subscription ON payments(subscription_id);
CREATE INDEX IF NOT EXISTS idx_payments_date         ON payments(payment_date);

-- The PHP app connects as the database owner (via the pooler string), which
-- bypasses RLS; enabling RLS with no policies blocks the public Supabase API
-- (anon/authenticated keys) from reading this data.
ALTER TABLE users         ENABLE ROW LEVEL SECURITY;
ALTER TABLE customers     ENABLE ROW LEVEL SECURITY;
ALTER TABLE plans         ENABLE ROW LEVEL SECURITY;
ALTER TABLE subscriptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE payments      ENABLE ROW LEVEL SECURITY;
